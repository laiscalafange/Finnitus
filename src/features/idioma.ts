export type ChaveIdioma = keyof typeof traducoes;

export function traduzir(idioma: Idioma, chave: ChaveIdioma, variaveis: Variaveis = {}) {
  const texto = idioma === "en" ? traducoes[chave][0]
    : idioma === "es" ? traducoes[chave][1] : chave;
  return texto.replace(/\{(\w+)\}/g, (marcador, nome) =>
    Object.hasOwn(variaveis, nome) ? String(variaveis[nome]) : marcador,
  );
}

export function useIdioma() {
  const { configuracoes } = useConfiguracoes();
  const idioma: Idioma = configuracoes?.idioma === "en" || configuracoes?.idioma === "es"
    ? configuracoes.idioma : "pt-BR";
  const t = useCallback((chave: ChaveIdioma, variaveis?: Variaveis) =>
    traduzir(idioma, chave, variaveis), [idioma]);
  return { idioma, t };
}
